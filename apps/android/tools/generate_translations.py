"""Generate Android resources and their literal-to-resource index. No dependencies."""
from pathlib import Path
import json
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/translations.json'
RES = ROOT / 'app/src/main/res'
JAVA = ROOT / 'app/src/main/java/com/agentbeacon/android'


def resource_id(english: str) -> str:
    return 'text_' + '_'.join(re.findall(r'[a-z0-9]+', english.lower())[:8])


def android_string(value: str) -> str:
    value = value.replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'").replace('\n', '\\n')
    return '"' + escape(value) + '"'


def main() -> None:
    entries = json.loads(SOURCE.read_text(encoding='utf-8'))
    seen = set()
    cases = []
    for folder, language in [('values', 'uk'), ('values-en', 'en')]:
        lines = ['<!-- Generated by tools/generate_translations.py; edit tools/translations.json. -->', '<resources>']
        for english, entry in entries.items():
            key = entry['id']
            lines.append(f'    <string name="{key}">{android_string(english if language == "en" else entry["uk"])}</string>')
            if language == 'uk':
                if key in seen:
                    raise ValueError('Duplicate resource ID: ' + key)
                seen.add(key)
                cases.append('            case ' + json.dumps(english, ensure_ascii=False) + ': return R.string.' + key + ';')
        lines.append('    <plurals name="tracked_chats">')
        forms = {'one': '%1$d tracked chat', 'other': '%1$d tracked chats'} if language == 'en' else {
            'one': '%1$d відстежуваний чат', 'few': '%1$d відстежувані чати', 'many': '%1$d відстежуваних чатів', 'other': '%1$d відстежуваного чату'}
        for quantity, value in forms.items():
            lines.append(f'        <item quantity="{quantity}">{android_string(value)}</item>')
        lines.extend(['    </plurals>', '</resources>'])
        output = RES / folder / 'strings.xml'
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    (JAVA / 'TextCatalog.java').write_text('''package com.agentbeacon.android;

/** Generated resource index. Only explicit UI messages pass through this catalog. */
final class TextCatalog {
    static int resource(String english) {
        switch (english) {
''' + '\n'.join(cases) + '''
            default: return 0;
        }
    }
    private TextCatalog() {}
}
''', encoding='utf-8')
    print('Generated', len(entries), 'matched Ukrainian/English Android strings')


if __name__ == '__main__':
    main()
